import { CanvasArtwork } from './CanvasArtwork'

export interface CreatureArtwork {
  body: CanvasArtwork
  tail: CanvasArtwork
  dorsal: CanvasArtwork
  pectoral: CanvasArtwork
}

function friendlyEye(g: CanvasArtwork, x: number, y: number, radius: number) {
  // One eye in a three-quarter view reads as a fish face at habitat scale.
  g.circle(x, y, radius + 0.35)
    .fill({ color: 0x294d42, alpha: 0.12 })
    .circle(x, y, radius)
    .fill(0xfffbed)
    .circle(x + radius * 0.2, y + radius * 0.02, radius * 0.58)
    .fill(0x294e43)
    .circle(x + radius * 0.39, y - radius * 0.28, radius * 0.2)
    .fill(0xffffff)
}

/** Original fish paths and colours, shared by all four cached animation frames. */
export function createCreatureArtwork(): [CreatureArtwork, CreatureArtwork] {
  const shark = new CanvasArtwork()
    .moveTo(18.5, -1)
    .bezierCurveTo(18.5, -8, 11, -11.8, 3, -11.4)
    .bezierCurveTo(-5, -11.1, -10, -6.2, -13, -2.4)
    .quadraticCurveTo(-15, 0, -13, 2.4)
    .bezierCurveTo(-9, 7.9, -2, 11, 7, 10.2)
    .bezierCurveTo(15, 9.5, 19.7, 5.1, 18.5, -1)
    .closePath()
    .fill(0xcc835b)
    .moveTo(-11, 2)
    .bezierCurveTo(-2, 5.4, 8, 5.5, 18.3, 1.4)
    .bezierCurveTo(18.2, 7.1, 12, 10, 6, 10.1)
    .bezierCurveTo(-3, 10.7, -9, 7, -11, 2)
    .closePath()
    .fill(0xf2d7aa)
    .moveTo(-5, -5.3)
    .bezierCurveTo(0, -9.1, 6, -9.7, 10.7, -7.3)
    .stroke({ color: 0xf1bc86, width: 1.4, alpha: 0.75 })
    .ellipse(12.5, 3.6, 2.6, 1.6)
    .fill({ color: 0xe6a080, alpha: 0.8 })
    .moveTo(17.1, 2.6)
    .quadraticCurveTo(15.3, 5.1, 12.9, 4.3)
    .stroke({ color: 0x946345, width: 0.8 })
    .moveTo(1, -1)
    .quadraticCurveTo(-0.3, 1, 0.6, 3)
    .moveTo(-1.5, -0.5)
    .quadraticCurveTo(-2.6, 1.2, -1.7, 2.8)
    .stroke({ color: 0xb27250, width: 0.65, alpha: 0.6 })
  friendlyEye(shark, 10.1, -2.8, 4.15)

  const sharkTail = new CanvasArtwork()
    .moveTo(1, -2)
    .quadraticCurveTo(-4, -2, -9, -7.2)
    .bezierCurveTo(-12, -10.1, -15, -8.4, -13.3, -4.1)
    .quadraticCurveTo(-12, -0.7, -11, 0)
    .quadraticCurveTo(-12, 0.7, -13.3, 4.1)
    .bezierCurveTo(-15, 8.4, -12, 10.1, -9, 7.2)
    .quadraticCurveTo(-4, 2, 1, 2)
    .closePath()
    .fill(0xc17a55)
    .moveTo(-3, 0)
    .quadraticCurveTo(-8, -0.4, -11, -5)
    .moveTo(-3, 0)
    .quadraticCurveTo(-8, 0.4, -11, 5)
    .stroke({ color: 0xe3ad78, width: 0.65, alpha: 0.75 })
  const sharkDorsal = new CanvasArtwork()
    .moveTo(-7, 0)
    .bezierCurveTo(-5, -3.4, -2, -10.2, 1, -10.7)
    .quadraticCurveTo(2.7, -10.9, 2.3, -8.7)
    .quadraticCurveTo(2, -3.3, 6, 0)
    .closePath()
    .fill(0xbd7853)
    .moveTo(-3, -1)
    .quadraticCurveTo(-1, -4, 1, -7)
    .stroke({ color: 0xdda375, width: 0.7, alpha: 0.7 })
  const sharkPectoral = new CanvasArtwork()
    .moveTo(3, -0.5)
    .bezierCurveTo(1, 3.9, -3, 7.8, -5.5, 7)
    .bezierCurveTo(-7.4, 6.1, -5.1, 1.7, -3, -0.9)
    .closePath()
    .fill(0xd59468)
    .moveTo(1, 1)
    .quadraticCurveTo(-1, 4, -4, 5.5)
    .stroke({ color: 0xf0c18a, width: 0.65, alpha: 0.8 })

  const minnow = new CanvasArtwork()
    .moveTo(12, -0.3)
    .bezierCurveTo(12, -5.6, 7.4, -8.5, 1.2, -8.1)
    .bezierCurveTo(-4.5, -7.8, -8, -4, -10, -1.5)
    .quadraticCurveTo(-11.2, 0, -10, 1.5)
    .bezierCurveTo(-6.3, 6.5, -0.1, 8.2, 5.7, 6.8)
    .bezierCurveTo(10.3, 5.7, 13, 3.6, 12, -0.3)
    .closePath()
    .fill(0x729b7f)
    .moveTo(-8, 1.5)
    .bezierCurveTo(-1, 3.6, 5, 4, 11.7, 1)
    .bezierCurveTo(10.8, 5.2, 6.9, 6.9, 3, 7.1)
    .bezierCurveTo(-2, 7.4, -6, 5, -8, 1.5)
    .closePath()
    .fill(0xd9e2bb)
    .moveTo(-4, -4)
    .quadraticCurveTo(1, -7, 5.6, -5.5)
    .stroke({ color: 0xa9c6a0, width: 1.1, alpha: 0.8 })
    .ellipse(8, 3, 1.8, 1.2)
    .fill({ color: 0xb7c491, alpha: 0.85 })
    .moveTo(11, 1.7)
    .quadraticCurveTo(9.7, 3.7, 8.1, 3)
    .stroke({ color: 0x567b5d, width: 0.65 })
  friendlyEye(minnow, 6.4, -2.1, 3.3)
  const minnowTail = new CanvasArtwork()
    .moveTo(1, -1.4)
    .quadraticCurveTo(-3, -1.4, -7, -5.4)
    .bezierCurveTo(-10, -7.4, -12, -5.8, -10.2, -2.6)
    .quadraticCurveTo(-8.6, 0, -10.2, 2.6)
    .bezierCurveTo(-12, 5.8, -10, 7.4, -7, 5.4)
    .quadraticCurveTo(-3, 1.4, 1, 1.4)
    .closePath()
    .fill(0x8caf8b)
    .moveTo(-2, 0)
    .lineTo(-8.5, -3.2)
    .moveTo(-2, 0)
    .lineTo(-8.5, 3.2)
    .stroke({ color: 0xb9cfa5, width: 0.55, alpha: 0.8 })
  const minnowDorsal = new CanvasArtwork()
    .moveTo(-5, 0)
    .quadraticCurveTo(-1, -5.8, 2, -5.3)
    .quadraticCurveTo(3.8, -4.8, 3.8, 0)
    .closePath()
    .fill(0x7fa585)
  const minnowPectoral = new CanvasArtwork()
    .moveTo(2, -0.4)
    .bezierCurveTo(0.4, 3.5, -2.2, 5.4, -4, 4.5)
    .quadraticCurveTo(-5.4, 3, -2, -1)
    .closePath()
    .fill(0x9db994)
    .moveTo(0.6, 0.7)
    .lineTo(-2.6, 3.4)
    .stroke({ color: 0xc4d5ac, width: 0.55 })

  return [
    { body: shark, tail: sharkTail, dorsal: sharkDorsal, pectoral: sharkPectoral },
    { body: minnow, tail: minnowTail, dorsal: minnowDorsal, pectoral: minnowPectoral },
  ]
}
